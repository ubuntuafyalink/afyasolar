export const DICTIONARIES: Record<Locale, Messages> = { en, sw }

/**
 * Translate a key for a locale, falling back to English, then to the raw key.
 * Supports simple `{name}` interpolation.
 */
export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const table = DICTIONARIES[locale] ?? DICTIONARIES[DEFAULT_LOCALE]
  let value = table[key] ?? DICTIONARIES[DEFAULT_LOCALE][key] ?? key
  if (vars) {
    for (const [name, v] of Object.entries(vars)) {
      value = value.replace(new RegExp(`\\{${name}\\}`, "g"), String(v))
    }
  }
  return value
}
